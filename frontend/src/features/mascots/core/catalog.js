export const ANIMATION_BY_ID = Object.fromEntries(ANIMATIONS.map((animation) => [animation.id, animation]));
export const ANIMATIONS_BY_CHARACTER = Object.fromEntries(
  CHARACTER_LIST.map((character) => [
    character.id,
    ANIMATIONS.filter((animation) => animation.character === character.id),
  ]),
);

export const CLIP_TO_ANIMATION = Object.fromEntries(
  ANIMATIONS.map((animation) => [animation.clip, animation]),
);

export const P1_ANIMATIONS = ANIMATIONS.filter((animation) => animation.p === 1);
export const P2_ANIMATIONS = ANIMATIONS.filter((animation) => animation.p === 2);
export const P3_ANIMATIONS = ANIMATIONS.filter((animation) => animation.p === 3);

export function getAnimation(id) {
  return ANIMATION_BY_ID[id] ?? CLIP_TO_ANIMATION[id] ?? null;
}

export function getAnimationsForCharacter(characterId, priority = null) {
  const items = ANIMATIONS_BY_CHARACTER[characterId] ?? [];
  return priority ? items.filter((animation) => animation.p === priority) : items;
}

export function getClipName(animationId) {
  return ANIMATION_BY_ID[animationId]?.clip ?? null;
}
