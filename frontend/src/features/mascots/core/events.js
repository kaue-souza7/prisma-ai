export const UX_EVENT_BY_ID = Object.fromEntries(UX_EVENTS.map((event) => [event.id, event]));

export function sequenceLabel(event) {
  if (!event) return '';
  return event.sequence
    .map((id) => {
      const animation = ANIMATION_BY_ID[id];
      return animation ? `${id} ${animation.name}` : id;
    })
    .join(' → ');
}
